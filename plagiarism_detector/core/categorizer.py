# -*- coding: utf-8 -*-
"""
وحدة التصنيف التلقائي للتخصصات (Smart Domain Categorization):
تستخدم خوارزمية استخراج الكلمات المفتاحية والأوزان التكرارية لتصنيف البحث تلقائيًا
إلى التخصص العلمي المناسب (قانون، طب، علوم تربوية، هندسة، إعلام، اقتصاد، علوم حاسب، عام).
"""

import re
from collections import Counter

DOMAIN_KEYWORDS = {
    'قانون وفقه': ['قانون', 'مادة', 'دستور', 'جريمة', 'محكمة', 'عقد', 'عقوبة', 'قضائي', 'مشرع', 'جنائي', 'حقوق', 'دعوى', 'تشريع'],
    'طب وعلوم صحية': ['مرض', 'علاج', 'عينة', 'تشخيص', 'سريري', 'مرضى', 'خلايا', 'جرعة', 'مستشفى', 'أطباء', 'جراحة', 'دم', 'وقاية'],
    'علوم تربوية وتعليم': ['طالب', 'طلاب', 'مدرسة', 'تدريس', 'منهج', 'تحصيل', 'معلم', 'تربية', 'تعليم', 'دراسي', 'جامعي', 'فصل', 'تقويم'],
    'اقتصاد وإدارة أعمال': ['سوق', 'بنك', 'استثمار', 'تضخم', 'أرباح', 'شركة', 'مالي', 'إدارة', 'أسهم', 'تجارة', 'اقتصاد', 'نمو', 'إنتاج'],
    'هندسة وتكنولوجيا': ['هندسة', 'تصميم', 'نظام', 'شبكة', 'برمجة', 'ذكاء', 'خوارزمية', 'بيانات', 'بيئة', 'طاقة', 'إنشاءات', 'تقنية', 'حاسب'],
    'إعلام وتواصل اجتماعي': ['إعلام', 'صحافة', 'جمهور', 'تواصل', 'رأي', 'قناة', 'محتوى', 'خبر', 'حملة', 'تأثير', 'وسائل'],
}


def categorize_text(text: str) -> str:
    """
    تحليل النص وتحديد التخصص العلمي الأقرب له تلقائيًا.
    """
    if not text:
        return 'عام'

    words = re.findall(r'[\u0600-\u06FF]+', text.lower())
    if not words:
        return 'عام'

    word_counts = Counter(words)
    domain_scores = {domain: 0 for domain in DOMAIN_KEYWORDS}

    for domain, kw_list in DOMAIN_KEYWORDS.items():
        for kw in kw_list:
            domain_scores[domain] += word_counts[kw] * 2
            # البحث عن المشتقات
            for w in word_counts:
                if kw in w and w != kw:
                    domain_scores[domain] += word_counts[w]

    best_domain, max_score = max(domain_scores.items(), key=lambda x: x[1])

    if max_score < 4:
        return 'عام'

    return best_domain
