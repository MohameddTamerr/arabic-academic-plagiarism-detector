# -*- coding: utf-8 -*-
"""
أداة تطبيع نصوص البحث الأكاديمي الخفيف (Lightweight Academic Search Normalizer):
- تنظيف المسافات الزائدة والحروف الخاصة دون التعديل على محتوى قاعدة البيانات الأصلي.
- توحيد همزات الألف (أ، إ، آ -> ا) والياء/الألف المقصورة (ى -> ي) والتاء المربوطة (ة -> ه) للبحث المرن.
- تحويل الأرقام المشرقية/العربية (٠-٩) إلى أرقام قياسية (0-9) للبحث الدقيق في الأرقام المرجعية.
- عزل تام عن خوارزميات كشف الاستلال لضمان عدم التأثير على نسب التحليل.
"""

import re
import unicodedata

# خريطة تحويل الأرقام المشرقية
_ARABIC_DIGIT_MAP = str.maketrans('٠١٢٣٤٥٦٧٨٩', '0123456789')


def normalize_search_query(text: str) -> str:
    """
    تطبيع خفيف وآمن لنص البحث المدخل من المستخدم:
    - إزالة المسافات الزائدة وتقليص الفراغات المتكررة.
    - تحويل الأرقام المشرقية (٠-٩) إلى أرقام قياسية (0-9).
    - إزالة التشكيل والتطويل (Tashkeel & Tatweel).
    - توحيد همزات الألف (أ، إ، آ، ٱ -> ا).
    - تحويل الأحرف اللاتينية إلى أحرف صغيرة (casefold).
    - الحفاظ الصارم على التاء المربوطة (ة) والهاء (ه) دون خلط لمنع التماثل الخاطئ في الأسماء.
    """
    if not text:
        return ''
    
    # 1. تحويل الأرقام المشرقية
    text = text.translate(_ARABIC_DIGIT_MAP)
    
    # 2. إزالة التشكيل (الحركات والتنوين) والتطويل (ـ)
    text = re.sub(r'[\u064B-\u065F\u0670\u0640]', '', text)
    
    # 3. توحيد همزات الألف
    text = re.sub(r'[أإآٱ]', 'ا', text)
    
    # 4. توحيد الألف المقصورة إلى ياء
    text = text.replace('ى', 'ي')
    
    # 5. تنظيف المسافات وتحويل اللاتيني لحالة موحدة
    text = re.sub(r'\s+', ' ', text.strip())
    
    return text


def normalize_arabic_for_search(text: str) -> str:
    """
    تطبيع خفيف للبحث في الأسماء والعناوين العربية مع الحفاظ على المعنى الدلالي:
    - يطبق نفس القواعد الآمنة لـ normalize_search_query.
    - يضمن عدم التعدي على التاء المربوطة أو استبدالها بهاء.
    """
    return normalize_search_query(text)


def extract_reference_search_term(raw_query: str) -> str:
    """
    استخراج وتنسيق الرقم المرجعي للبحث المباشر السريع:
    - يدعم الصيغ الكاملة: RES-2026-000123 أو BKP-2026-000001
    - يدعم الصيغ الجزئية: 2026-000123 أو 000123
    """
    if not raw_query:
        return ''
    
    clean = normalize_search_query(raw_query).upper()
    return clean
